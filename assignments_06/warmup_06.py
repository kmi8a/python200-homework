# --- Semantic RAG Concepts ---

# Semantic Q1

# Question: What is a vector embedding? (1-2 sentences)
# Answer: A vector embedding is a number or list of numbers assigned to a word (or piece of data) that maps it into a numerical space. 
# these embeddings then represent properties of the data so the model can understand it.

# Question:Two text chunks have cosine similarity scores of 0.85 and 0.30 with a given query. Which chunk is more relevant, and what does that number tell you about the relationship between the texts?
# Answer: Cosine similarity goes from -1 to 1, so in this scale 0.85 being closer to 1 makes it more relevant to the query, 0.30 has some relevancy, a number 0 would mean no relevancy. 

# Question:Why can semantic search find a relevant chunk even when none of the exact words from the query appear in the chunk?
# Answer: Using the embeddings and their position on the numerical space, then comparing those positions with the positions of the word used in the query, semantic search finds
# relevance through the distance between words using cosine similarity.

# Semantic Q2

# | Feature                    | Keyword RAG                       | Semantic RAG                             |
# |----------------------------|-----------------------------------|------------------------------------------|
# | What is compared?          | Exact word overlap                | Distance in the numerical space          |
# | What is retrieved?         | Full document                     | A Chunk of the document                  |
# | Can it handle synonyms?    | No                                | Yes                                      |
# | Storage format             | Plain text dictionary             | Vector database                          |
# | Relevance score            | Number of overlapping keywords    | Cosine similarity                        |


