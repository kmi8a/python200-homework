# Concepts Q3

# 1. Extract text from source documents - The content of the documents is extracted from the source files.
# 2. Split text into chunks - Read text is then split into smaller, manageable chunks for retrieval.
# 3. Convert text chunks into embeddings - Text chunks are converted to embeddings and then stored in a vector database.
# 4. Receive the user's query - The model receives the user's query.
# 5. Embed the user's query - The query gets converted to an embedding, so it is on the same vector space as the text chunks done before.
# 6. Retrieve the most relevant chunks - Most relevant chunks get retrieved, most relevant meaning they are closer in the vector space.
# 7. Inject retrieved chunks into the prompt - The prompt is then augmented using the relevant chunks of text.
# 8. Generate a response from the LLM - A response is generated by the LLM using the augmented context.


# --- Keyword RAG ---

def simple_keyword_retrieval(query, documents, verbose=True):
    """Keyword retrieval using token overlap scoring."""
    stopwords = {
        "a", "an", "the", "and", "or", "in", "on", "of", "for", "to", "is",
        "are", "was", "were", "by", "with", "at", "from", "that", "this",
        "as", "be", "it", "its", "their", "they", "we", "you", "our"
    }
    translator = str.maketrans("", "", string.punctuation)

    query_words = {
        w.translate(translator)
        for w in query.lower().split()
        if w not in stopwords
    }
    if verbose:
        print(f"\nQuery tokens (filtered): {sorted(query_words)}")

    scores = []
    for name, content in documents.items():
        content_words = {
            w.translate(translator)
            for w in content.lower().split()
            if w not in stopwords
        }
        overlap = query_words & content_words
        score = len(overlap)
        scores.append((score, name, content))
        if verbose:
            print(f"[{name}] overlap={score} -> {sorted(overlap)}")

    scores.sort(reverse=True)
    best = next(((name, content) for score, name, content in scores if score > 0), None)
    if best:
        if verbose:
            print(f"\nSelected best match: {best[0]}")
        return [best]
    else:
        if verbose:
            print("\nNo overlapping keywords found.")
        return [("None found", "No relevant content.")]

